// @vitest-environment jsdom
import { render, screen, fireEvent, waitFor, cleanup } from '@testing-library/react'
import { vi, beforeEach, afterEach, expect, test } from 'vitest'
import { AssessmentHistory } from './AssessmentHistory'
import { ApiError, request } from './api'
vi.mock('./api', async () => ({ ...await vi.importActual('./api'), request: vi.fn() }))
afterEach(cleanup)
const session = { token: 'SYNTHETIC', expiresAt: '2099-01-01T00:00:00Z' }
const onExpired = vi.fn()
beforeEach(() => { vi.resetAllMocks() })
test('only loads authorized read projection on demand and has no editing controls', async () => {
  vi.mocked(request).mockResolvedValue({ data: [{ id: 'SYNTHETIC', date_wib: '2026-11-07', study_day: 1, vas_mm: 0, filled_by: 'PASIEN', received_at: '2026-11-07T01:00:00Z', version: 'SYNTHETIC-V1', answers: [{ code: 'SYNTHETIC_ITEM', value: 'SYNTHETIC_A' }] }], meta: { last_page: 1 } })
  render(<AssessmentHistory participantId="SYNTHETIC" session={session} onExpired={onExpired} />)
  expect(request).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Lihat riwayat assessment' }))
  await screen.findByText('SYNTHETIC_ITEM: SYNTHETIC_A')
  expect(request).toHaveBeenCalledWith('/participants/SYNTHETIC/assessments?page=1', session.token, 'GET', undefined, expect.any(AbortSignal))
  expect(screen.queryByRole('textbox')).toBeNull()
  expect(screen.getByText(/Jawaban tersimpan tidak dapat diedit/)).toBeTruthy()
})
test('denial reveals no data and expiration invalidates the researcher session', async () => {
  vi.mocked(request).mockRejectedValueOnce(new ApiError(403))
  render(<AssessmentHistory participantId="SYNTHETIC" session={session} onExpired={onExpired} />)
  fireEvent.click(screen.getByRole('button', { name: 'Lihat riwayat assessment' }))
  await screen.findByRole('alert'); expect(screen.queryByText(/VAS/)).toBeNull()
  vi.mocked(request).mockRejectedValueOnce(new ApiError(401))
  fireEvent.click(screen.getByRole('button', { name: 'Coba lagi' }))
  await waitFor(() => expect(onExpired).toHaveBeenCalled())
})
test('closing aborts read and a late response does not appear', async () => {
  let resolve!: (data: unknown) => void
  vi.mocked(request).mockImplementation(() => new Promise(done => { resolve = done }))
  render(<AssessmentHistory participantId="SYNTHETIC" session={session} onExpired={onExpired} />)
  fireEvent.click(screen.getByRole('button', { name: 'Lihat riwayat assessment' }))
  fireEvent.click(screen.getByRole('button', { name: 'Tutup riwayat assessment' }))
  expect(vi.mocked(request).mock.calls[0][4]?.aborted).toBe(true)
  resolve({ data: [], meta: { last_page: 1 } })
  expect(screen.queryByText('Belum ada assessment tersimpan.')).toBeNull()
})
test('applies inclusive date/type filters only after confirmation and requires the server echo', async () => {
  vi.mocked(request).mockResolvedValue({ data: [], meta: { last_page: 1, total: 0, filters: { from: null, to: null, type: null } } })
  render(<AssessmentHistory participantId="SYNTHETIC" session={session} onExpired={onExpired} />)
  fireEvent.click(screen.getByRole('button', { name: 'Lihat riwayat assessment' }))
  await screen.findByText('Belum ada assessment tersimpan.')
  fireEvent.change(screen.getByLabelText('Dari tanggal WIB'), { target: { value: '2026-11-07' } })
  fireEvent.change(screen.getByLabelText('Sampai tanggal WIB'), { target: { value: '2026-11-08' } })
  fireEvent.change(screen.getByLabelText('Jenis catatan'), { target: { value: 'HARIAN' } })
  expect(request).toHaveBeenCalledTimes(1)
  vi.mocked(request).mockResolvedValue({ data: [{ id: 'SYNTHETIC', date_wib: '2026-11-07', study_day: 1, vas_mm: 100, type: 'HARIAN', filled_by: 'KELUARGA', received_at: '2026-11-07T01:00:00Z', version: 'SYNTHETIC-V1', answers: [{ code: 'SYNTHETIC_ITEM', value: 'SYNTHETIC_A', question_label: 'Pertanyaan sintetis lama', answer_label: 'Jawaban sintetis lama' }] }], meta: { last_page: 1, total: 1, filters: { from: '2026-11-07', to: '2026-11-08', type: 'HARIAN' } } })
  fireEvent.click(screen.getByRole('button', { name: 'Terapkan filter assessment' }))
  await screen.findByText('Pertanyaan sintetis lama: Jawaban sintetis lama')
  expect(request).toHaveBeenLastCalledWith('/participants/SYNTHETIC/assessments?page=1&from=2026-11-07&to=2026-11-08&type=HARIAN', session.token, 'GET', undefined, expect.any(AbortSignal))
  expect(screen.getByText('Tersimpan (server) · HARIAN')).toBeTruthy()
  vi.mocked(request).mockResolvedValue({ data: [{ id: 'WRONG-UNFILTERED', date_wib: '2026-01-01', vas_mm: 99, answers: [] }], meta: { last_page: 1, total: 1 } })
  fireEvent.click(screen.getByRole('button', { name: 'Muat ulang assessment' }))
  await screen.findByText(/Filter server belum terverifikasi/)
  expect(screen.queryByText(/VAS 100/)).toBeNull(); expect(screen.queryByText(/VAS 99/)).toBeNull()
})
test('reversed dates do not request or submit the containing enrollment form; Enter applies safely', async () => {
  const submit = vi.fn(event => event.preventDefault())
  vi.mocked(request).mockResolvedValue({ data: [], meta: { last_page: 1, total: 0, filters: { from: null, to: null, type: null } } })
  render(<form onSubmit={submit}><AssessmentHistory participantId="SYNTHETIC" session={session} onExpired={onExpired} /></form>)
  fireEvent.click(screen.getByRole('button', { name: 'Lihat riwayat assessment' }))
  await screen.findByText('Belum ada assessment tersimpan.')
  fireEvent.change(screen.getByLabelText('Dari tanggal WIB'), { target: { value: '2026-11-08' } })
  fireEvent.change(screen.getByLabelText('Sampai tanggal WIB'), { target: { value: '2026-11-07' } })
  fireEvent.keyDown(screen.getByLabelText('Sampai tanggal WIB'), { key: 'Enter' })
  expect(screen.getByText(/Tanggal akhir tidak boleh/)).toBeTruthy()
  expect(request).toHaveBeenCalledTimes(1); expect(submit).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Hapus filter assessment' }))
  await waitFor(() => expect(request).toHaveBeenCalledTimes(2))
  expect(submit).not.toHaveBeenCalled()
})
test('participant and token changes abort prior monitoring reads and hide stale data', async () => {
  let resolve!: (data: unknown) => void
  vi.mocked(request).mockImplementationOnce(() => new Promise(done => { resolve = done }))
    .mockResolvedValue({ data: [], meta: { last_page: 1, total: 0 } })
  const { rerender } = render(<AssessmentHistory participantId="SYNTHETIC-A" session={session} onExpired={onExpired} />)
  fireEvent.click(screen.getByRole('button', { name: 'Lihat riwayat assessment' }))
  rerender(<AssessmentHistory participantId="SYNTHETIC-B" session={{ ...session, token: 'OTHER-SYNTHETIC' }} onExpired={onExpired} />)
  expect(vi.mocked(request).mock.calls[0][4]?.aborted).toBe(true)
  resolve({ data: [{ id: 'OLD', date_wib: '2026-11-07', vas_mm: 99, answers: [] }], meta: { last_page: 1 } })
  await screen.findByText('Belum ada assessment tersimpan.')
  expect(screen.queryByText(/VAS 99/)).toBeNull()
  expect(screen.getByText(/Antrean lokal pasien tidak terlihat/)).toBeTruthy()
})
test('pagination retains filters and a mismatched echo cannot show broader observations', async () => {
  vi.mocked(request).mockResolvedValue({ data: [], meta: { last_page: 2, total: 26, filters: { from: null, to: null, type: null } } })
  render(<AssessmentHistory participantId="SYNTHETIC" session={session} onExpired={onExpired} />)
  fireEvent.click(screen.getByRole('button', { name: 'Lihat riwayat assessment' }))
  await screen.findByText('Belum ada assessment tersimpan.')
  fireEvent.change(screen.getByLabelText('Dari tanggal WIB'), { target: { value: '2026-11-07' } })
  vi.mocked(request).mockResolvedValue({ data: [], meta: { last_page: 2, total: 26, filters: { from: '2026-11-07', to: null, type: null } } })
  fireEvent.click(screen.getByRole('button', { name: 'Terapkan filter assessment' }))
  await screen.findByText('Belum ada assessment tersimpan.')
  fireEvent.click(screen.getByRole('button', { name: 'Assessment berikutnya' }))
  await waitFor(() => expect(request).toHaveBeenLastCalledWith('/participants/SYNTHETIC/assessments?page=2&from=2026-11-07', session.token, 'GET', undefined, expect.any(AbortSignal)))
  await screen.findByText('26 catatan tersimpan dalam hasil · halaman 2 dari 2.')
  vi.mocked(request).mockResolvedValue({ data: [{ id: 'BROAD', vas_mm: 99 }], meta: { last_page: 1, filters: { from: null, to: null, type: null } } })
  fireEvent.click(screen.getByRole('button', { name: 'Muat ulang assessment' }))
  await screen.findByText(/Filter server belum terverifikasi/)
  expect(screen.queryByText(/VAS 99/)).toBeNull()
})
